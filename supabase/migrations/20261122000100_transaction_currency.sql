-- Per-trade currency is required for portfolios that span multiple exchanges.
-- Existing rows are backfilled from the listing venue; users can correct exceptions.
ALTER TABLE public.transactions
  ADD COLUMN IF NOT EXISTS currency text;

UPDATE public.transactions AS t
SET currency = COALESCE(
  CASE UPPER(BTRIM(t.exchange))
    WHEN 'PSX' THEN 'PKR' WHEN 'KSE' THEN 'PKR' WHEN 'KSE100' THEN 'PKR'
    WHEN 'NSE' THEN 'INR' WHEN 'BSE' THEN 'INR' WHEN 'XNSE' THEN 'INR' WHEN 'XBOM' THEN 'INR'
    WHEN 'NYSE' THEN 'USD' WHEN 'NASDAQ' THEN 'USD' WHEN 'AMEX' THEN 'USD' WHEN 'CBOE' THEN 'USD' WHEN 'OTC' THEN 'USD'
    WHEN 'XNYS' THEN 'USD' WHEN 'XNAS' THEN 'USD'
    WHEN 'LSE' THEN 'GBP' WHEN 'AIM' THEN 'GBP' WHEN 'XLON' THEN 'GBP'
    WHEN 'TSX' THEN 'CAD' WHEN 'TSXV' THEN 'CAD' WHEN 'CNSX' THEN 'CAD' WHEN 'XTSE' THEN 'CAD'
    WHEN 'ASX' THEN 'AUD' WHEN 'XASX' THEN 'AUD'
    WHEN 'NZX' THEN 'NZD'
    WHEN 'HKEX' THEN 'HKD' WHEN 'XHKG' THEN 'HKD'
    WHEN 'TSE' THEN 'JPY' WHEN 'JPX' THEN 'JPY' WHEN 'OSE' THEN 'JPY' WHEN 'XTKS' THEN 'JPY'
    WHEN 'KRX' THEN 'KRW' WHEN 'KOSDAQ' THEN 'KRW' WHEN 'XKRX' THEN 'KRW'
    WHEN 'SGX' THEN 'SGD' WHEN 'XSES' THEN 'SGD'
    WHEN 'SIX' THEN 'CHF' WHEN 'SWX' THEN 'CHF' WHEN 'BX' THEN 'CHF' WHEN 'XSWX' THEN 'CHF'
    WHEN 'XETRA' THEN 'EUR' WHEN 'XETR' THEN 'EUR' WHEN 'FRA' THEN 'EUR' WHEN 'ETR' THEN 'EUR'
    WHEN 'EURONEXT' THEN 'EUR' WHEN 'EPA' THEN 'EUR' WHEN 'AMS' THEN 'EUR' WHEN 'EBR' THEN 'EUR' WHEN 'ELI' THEN 'EUR'
    WHEN 'BIT' THEN 'EUR' WHEN 'BME' THEN 'EUR' WHEN 'VIE' THEN 'EUR' WHEN 'ATHEX' THEN 'EUR' WHEN 'HEL' THEN 'EUR'
    WHEN 'WSE' THEN 'PLN' WHEN 'STO' THEN 'SEK' WHEN 'OSL' THEN 'NOK' WHEN 'CPH' THEN 'DKK'
    WHEN 'PRA' THEN 'CZK' WHEN 'BUD' THEN 'HUF'
    WHEN 'B3' THEN 'BRL' WHEN 'BMV' THEN 'MXN' WHEN 'BVL' THEN 'PEN' WHEN 'CASA' THEN 'MAD' WHEN 'BCBA' THEN 'ARS'
    WHEN 'SSE' THEN 'CNY' WHEN 'SZSE' THEN 'CNY' WHEN 'TWSE' THEN 'TWD' WHEN 'TPEX' THEN 'TWD'
    WHEN 'IDX' THEN 'IDR' WHEN 'MYX' THEN 'MYR' WHEN 'SET' THEN 'THB' WHEN 'HOSE' THEN 'VND' WHEN 'HNX' THEN 'VND'
    WHEN 'PSE' THEN 'PHP' WHEN 'CSE' THEN 'LKR' WHEN 'DSE' THEN 'BDT'
    WHEN 'TADAWUL' THEN 'SAR' WHEN 'ADX' THEN 'AED' WHEN 'DFM' THEN 'AED' WHEN 'QSE' THEN 'QAR'
    WHEN 'BIST' THEN 'TRY' WHEN 'TASE' THEN 'ILS' WHEN 'JSE' THEN 'ZAR' WHEN 'NGX' THEN 'NGN' WHEN 'EGX' THEN 'EGP'
    WHEN 'NSEKE' THEN 'KES' WHEN 'KWSE' THEN 'KWD'
    ELSE NULL
  END,
  'USD'
)
WHERE t.currency IS NULL OR BTRIM(t.currency) = '';

ALTER TABLE public.transactions
  ALTER COLUMN currency SET DEFAULT 'USD',
  ALTER COLUMN currency SET NOT NULL;

COMMENT ON COLUMN public.transactions.currency IS
  'Currency in which this individual trade price, fees and withholding are denominated; distinct from broker account base currency.';
